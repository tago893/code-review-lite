import { execFile } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { promisify } from "node:util";
import type { MetricsSnapshot } from "../observability/metrics.js";

const run = promisify(execFile);
const MAX_GIT_OUTPUT = 64 * 1024 * 1024;
const SHA = /^[0-9a-f]{40}$/;

/** What the trusted side needs from a source of changes. */
export interface LoadedInput {
  readonly diffText: string;
  readonly repoRoot: string;
  /**
   * The commit the change is reviewed against: the merge base of the requested base and the head. When the requested base
   * is an ancestor of the head (the usual case) this is the requested base itself.
   */
  readonly baseSha: string;
  /** The base as requested, resolved to a SHA. Differs from `baseSha` when the target branch has moved on since the branch point. */
  readonly requestedBaseSha: string;
  readonly headSha: string;
  /** Commits in the pull request (reachable from head, not from the review base), oldest first. SHAs only, never messages. */
  readonly commitShas: readonly string[];
}

export interface InputProvider {
  load(): Promise<LoadedInput>;
}

export interface OutputSink {
  write(report: string, metrics: MetricsSnapshot): Promise<void>;
}

/** A fixed-code input failure. The message never quotes git output, paths or revisions. */
export class InputError extends Error {
  constructor(readonly code: "bad_revision" | "rev_not_found" | "no_merge_base" | "head_not_checked_out" | "tree_not_clean" | "git_failed" | "diff_mismatch" | "diff_unreadable") {
    super(code);
    this.name = "InputError";
  }
}

export interface LocalGitOptions {
  readonly repoDir: string;
  readonly base: string;
  readonly head: string;
  /** Optional caller-supplied diff. Accepted only if it equals the diff regenerated from the pinned revisions. */
  readonly diffFile?: string;
}

/** Fixed diff options, so the output never depends on the repository's or the user's git configuration. */
const DIFF_OPTIONS = ["--no-ext-diff", "--no-textconv", "--no-color", "--binary", "--find-renames", "--src-prefix=a/", "--dst-prefix=b/"] as const;
const MAX_COMMITS = 1000;

/**
 * Reads a change from a local checkout. Revisions are resolved to SHAs once and pinned; HEAD must be the head SHA
 * and the working tree clean, so the files the reviewers read match the diff they review. The change is the net diff from
 * the merge base of base and head to the head: for a pull request that is exactly what the pull request changes, even
 * when the target branch has moved on since, and intermediate commits matter only through the final state. When the base
 * is already an ancestor of the head the merge base is the base, so nothing differs from a plain base..head diff.
 * The diff is always regenerated by git (no external diff or textconv drivers, fixed rename and prefix options); a
 * supplied --diff file is a cross-check, never a source. Arguments go to git as an array (no shell), and revisions
 * beginning with "-" are refused.
 */
export function localGitProvider(options: LocalGitOptions): InputProvider {
  const git = async (args: readonly string[]): Promise<string> => {
    try {
      const { stdout } = await run("git", ["-C", options.repoDir, "--no-optional-locks", "-c", "core.fsmonitor=false", ...args], {
        maxBuffer: MAX_GIT_OUTPUT, env: { PATH: process.env.PATH ?? "", HOME: process.env.HOME ?? "", GIT_TERMINAL_PROMPT: "0" },
      });
      return stdout;
    } catch {
      throw new InputError("git_failed");
    }
  };
  const resolve = async (rev: string): Promise<string> => {
    if (rev.length === 0 || rev.startsWith("-")) throw new InputError("bad_revision");
    const out = await git(["rev-parse", "--verify", "--end-of-options", `${rev}^{commit}`]).catch(() => { throw new InputError("rev_not_found"); });
    const sha = out.trim();
    if (!SHA.test(sha)) throw new InputError("rev_not_found");
    return sha;
  };

  return {
    async load(): Promise<LoadedInput> {
      const [requestedBaseSha, headSha] = [await resolve(options.base), await resolve(options.head)];
      if ((await git(["rev-parse", "HEAD"])).trim() !== headSha) throw new InputError("head_not_checked_out");
      if ((await git(["status", "--porcelain", "--untracked-files=all"])).trim() !== "") throw new InputError("tree_not_clean");
      const baseSha = (await git(["merge-base", requestedBaseSha, headSha]).catch(() => { throw new InputError("no_merge_base"); })).trim();
      if (!SHA.test(baseSha)) throw new InputError("no_merge_base");
      const diffText = await git(["diff", ...DIFF_OPTIONS, baseSha, headSha]);
      if (options.diffFile !== undefined) await checkSuppliedDiff(options.diffFile, diffText);
      const commitShas = (await git(["rev-list", "--reverse", `--max-count=${MAX_COMMITS}`, `${baseSha}..${headSha}`])).split(/\r?\n/).filter((l) => SHA.test(l));
      return { diffText, repoRoot: options.repoDir, baseSha, requestedBaseSha, headSha, commitShas };
    },
  };
}

const normalise = (text: string): string => text.replace(/\r\n/g, "\n").replace(/\n+$/, "");

async function checkSuppliedDiff(path: string, regenerated: string): Promise<void> {
  const supplied = await readFile(path, "utf8").catch(() => { throw new InputError("diff_unreadable"); });
  if (normalise(supplied) !== normalise(regenerated)) throw new InputError("diff_mismatch");
}

/** Writes the report to `outFile` and the metrics next to it as metrics.json. */
export function fileSink(outFile: string): OutputSink {
  return {
    async write(report, metrics): Promise<void> {
      await mkdir(dirname(outFile), { recursive: true });
      await writeFile(outFile, report, "utf8");
      await writeFile(join(dirname(outFile), "metrics.json"), `${JSON.stringify(metrics, null, 2)}\n`, "utf8");
    },
  };
}
